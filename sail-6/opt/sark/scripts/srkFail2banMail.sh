#!/bin/bash
#
# Generate or remove /etc/fail2ban/jail.d/sail-mail.conf so fail2ban sends
# ban notices when Network SMTP (ssmtp) and Globals SUPEMAIL/EMAILALERT are set,
# and mail preference is not forced off (/opt/sark/cache/f2b-mail.pref).
#
set -e

MAILCONF=/etc/fail2ban/jail.d/sail-mail.conf
SSMTP=/etc/ssmtp/ssmtp.conf
DB=/opt/sark/db/sark.db
MAILPREF=/opt/sark/cache/f2b-mail.pref
RELOAD=1

usage() {
	echo "Usage: $0 [--no-reload]" >&2
}

while [ $# -gt 0 ]; do
	case "$1" in
		--no-reload) RELOAD=0; shift ;;
		-h|--help) usage; exit 0 ;;
		*) usage; exit 2 ;;
	esac
done

mkdir -p /etc/fail2ban/jail.d

is_placeholder_hub() {
	# "mail" is a valid ssmtp mailhub name (simple local MTA alias), not a stub.
	case "$1" in
		""|localhost|127.0.0.1|::1) return 0 ;;
		*) return 1 ;;
	esac
}

get_mailhub() {
	[ -f "$SSMTP" ] || return 0
	awk -F= '/^[[:space:]]*mailhub=/ {
		v=$2
		sub(/^[[:space:]]+/,"",v)
		sub(/[[:space:]]+$/,"",v)
		print v
		exit
	}' "$SSMTP"
}

get_dest() {
	[ -f "$DB" ] || return 0
	sqlite3 "$DB" "SELECT COALESCE(NULLIF(trim(SUPEMAIL),''), NULLIF(trim(EMAILALERT),'')) FROM globals WHERE pkey='global' LIMIT 1;" 2>/dev/null || true
}

get_pref() {
	# on | off | auto (missing file)
	if [ -f "$MAILPREF" ]; then
		tr '[:upper:]' '[:lower:]' < "$MAILPREF" | tr -d '[:space:]'
	else
		echo auto
	fi
}

HUB=$(get_mailhub)
HUB_HOST=${HUB%%:*}
DEST=$(get_dest)
PREF=$(get_pref)

remove_mail() {
	local why=${1:-SMTP or alert email unavailable}
	if [ -e "$MAILCONF" ]; then
		rm -f "$MAILCONF"
		echo "srkFail2banMail: removed $MAILCONF ($why)"
	fi
}

reload_f2b() {
	[ "$RELOAD" = "1" ] || return 0
	command -v fail2ban-client >/dev/null 2>&1 || return 0
	if fail2ban-client -t >/dev/null 2>&1; then
		fail2ban-client reload >/dev/null 2>&1 || systemctl reload fail2ban >/dev/null 2>&1 || true
	else
		echo "srkFail2banMail: warning: fail2ban-client -t failed; not reloading" >&2
		return 1
	fi
}

if [ "$PREF" = "off" ] || [ "$PREF" = "no" ]; then
	remove_mail "mail preference off"
	reload_f2b || true
	exit 0
fi

if is_placeholder_hub "$HUB_HOST" || [ -z "$DEST" ]; then
	remove_mail
	reload_f2b || true
	exit 0
fi

case "$DEST" in
	*@*.*) ;;
	*)
		echo "srkFail2banMail: ignoring invalid destemail '$DEST'" >&2
		remove_mail "invalid destemail"
		reload_f2b || true
		exit 0
		;;
esac

HOST=$(hostname -f 2>/dev/null || hostname)
umask 022
cat > "$MAILCONF" <<EOF
# Generated by srkFail2banMail.sh — do not edit by hand
[DEFAULT]
destemail = $DEST
sender = fail2ban@$HOST
mta = sendmail
action = %(action_mw)s
EOF

echo "srkFail2banMail: wrote $MAILCONF (destemail=$DEST pref=$PREF)"
reload_f2b || true
exit 0
